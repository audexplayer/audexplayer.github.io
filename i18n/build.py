"""Builds the translated copies of the site from the English pages.

The English pages at the repo root are the only source. For each language in LANGS this script
writes /<lang>/... copies, translating every unit of text through i18n/<lang>.json. A unit is the
content of a paragraph, heading, list item, button and so on (inline markup such as <b>, <a> and
<code> included), or a translatable attribute. Units are keyed by a short hash of their English text
(listed with the text in i18n/en.json), so a reworded English unit shows up as untranslated.

    python i18n/build.py extract   # list English units missing from any language file
    python i18n/build.py build     # write /ar, /de, /es, /pt-br (fails if a unit is untranslated)

Edit the English page, run `extract`, add the new units to each language file, then run `build`.
Never edit the generated /<lang>/ pages by hand: the next build overwrites them.

Requires beautifulsoup4 (pip install beautifulsoup4).
"""
import hashlib
import json
import os
import re
import sys

from bs4 import BeautifulSoup, Comment, NavigableString, Tag

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = ["index.html", "help/index.html", "help/raspberry-pi/index.html",
         "privacy-policy/index.html", "delete-account/index.html"]
# lang code -> (URL folder, <html lang>, direction, Google Play hl, Google sign-in locale)
LANGS = {
    "ar": ("ar", "ar", "rtl", "ar", "ar"),
    "de": ("de", "de", "ltr", "de", "de"),
    "es": ("es", "es", "ltr", "es", "es"),
    "pt-br": ("pt-br", "pt-BR", "ltr", "pt-BR", "pt-BR"),
}
GENERATED_NOTE = " Generated by i18n/build.py from the English page. Do not edit: change the English page and i18n/{lang}.json, then rebuild. "

BLOCK = {"address", "article", "aside", "blockquote", "body", "details", "dd", "div", "dl", "dt",
         "fieldset", "figcaption", "figure", "footer", "form", "h1", "h2", "h3", "h4", "h5", "h6",
         "head", "header", "hr", "html", "li", "main", "nav", "ol", "p", "pre", "section", "summary",
         "table", "tbody", "td", "th", "thead", "tr", "ul", "button", "title", "template"}
SKIP = {"script", "style", "svg", "pre", "code", "noscript", "iframe", "img", "br", "link", "meta"}
TRANSLATABLE_ATTRS = ("alt", "aria-label", "title", "placeholder", "data-title")
# Internal page paths that get the language folder; everything else (assets) stays as is.
PAGE_LINK = re.compile(r"^/(?:$|#|help/|privacy-policy/|delete-account/)")


def uid(key):
    return hashlib.sha1(key.encode("utf-8")).hexdigest()[:10]


def norm(html):
    return re.sub(r"\s+", " ", html).strip()


def has_letters(s):
    return re.search(r"[^\W\d_]", s) is not None


def excluded(node):
    """Inline content left out of a unit entirely: the wordmark, the picker's language names."""
    for el in [node] + list(node.parents):
        if not isinstance(el, Tag):
            continue
        cls = el.get("class") or []
        if el.get("translate") == "no" or "word" in cls or "lang-list" in cls or "lang-current" in cls:
            return True
    return False


def skipped(node):
    """True for anything the translator must not touch: code, brand wordmark, the language picker."""
    for el in [node] + list(node.parents):
        if not isinstance(el, Tag):
            continue
        if el.name in SKIP or el.get("translate") == "no":
            return True
        cls = el.get("class") or []
        if "word" in cls or "lang-list" in cls or "lang-current" in cls:
            return True
    return False


def is_block(node):
    return isinstance(node, Tag) and (node.name in BLOCK or any(
        isinstance(d, Tag) and d.name in BLOCK for d in node.descendants))


def runs(container):
    """Maximal runs of inline children of `container`, each trimmed of text-less nodes at either end."""
    out, cur = [], []
    for child in list(container.children):
        if isinstance(child, Comment):
            continue
        if is_block(child) or (isinstance(child, Tag) and child.name in SKIP and child.name not in ("code", "br", "img", "svg")):
            if cur:
                out.append(cur)
            cur = []
        else:
            cur.append(child)
    if cur:
        out.append(cur)
    trimmed = []
    for r in out:
        r = [n for n in r if not (isinstance(n, Tag) and excluded(n))]
        while r and not has_letters(text_of(r[0])):
            r = r[1:]
        while r and not has_letters(text_of(r[-1])):
            r = r[:-1]
        if not r:
            continue
        lettered = [n for n in r if has_letters(text_of(n))]
        if len(r) == 1 and isinstance(r[0], Tag):
            # A lone element (a link, a label span): translate what's inside it, keeping the element.
            trimmed.extend(runs(r[0]))
        elif len(lettered) > 1 and all(isinstance(n, Tag) for n in lettered):
            # A row of separate items (nav links, chips, pills) with no text between them: one unit
            # per item rather than one for the whole row.
            for n in lettered:
                if not skipped(n):
                    trimmed.extend(runs(n))
                else:
                    trimmed.append([n])
        else:
            trimmed.append(r)
    return trimmed


def text_of(node):
    """The node's text, leaving out anything the translator skips (the wordmark, code)."""
    if not isinstance(node, Tag):
        return "" if isinstance(node, Comment) else str(node)
    return "".join(str(t) for t in node.find_all(string=True)
                   if not isinstance(t, Comment) and not excluded(t.parent))


def units(soup):
    """Yield (kind, payload, key): text runs and translatable attributes, in document order."""
    for el in soup.find_all(True):
        if not skipped(el) and (el.name in BLOCK or el is soup):
            for r in runs(el):
                key = norm("".join(str(n) for n in r))
                yield ("run", r, key)
        # Attributes are translated on images and iframes too (alt, title), just not inside code.
        if excluded(el) or el.name in ("script", "style") or el.find_parent(["pre", "code", "script"]):
            continue
        for attr in TRANSLATABLE_ATTRS:
            v = el.get(attr)
            if isinstance(v, str) and has_letters(v):
                yield ("attr", (el, attr), norm(v))
        for attr, v in list(el.attrs.items()):
            if attr.startswith("data-msg-") and has_letters(v):
                yield ("attr", (el, attr), norm(v))
        if el.name == "meta" and el.get("name") == "description":
            yield ("attr", (el, "content"), norm(el["content"]))
    # <title> has no children of its own in BLOCK terms; handled as a block above.


def load(lang):
    path = os.path.join(ROOT, "i18n", f"{lang}.json")
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def read_page(page):
    with open(os.path.join(ROOT, page), encoding="utf-8") as f:
        return f.read()


def extract():
    seen, order = set(), []
    for page in PAGES:
        soup = BeautifulSoup(read_page(page), "html.parser")
        for kind, _, key in units(soup):
            if key not in seen:
                seen.add(key)
                order.append((page, key))
    with open(os.path.join(ROOT, "i18n", "en.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump({uid(k): k for _, k in order}, f, ensure_ascii=False, indent=1)
    ids = {uid(k) for k in seen}
    missing_any = False
    for lang in LANGS:
        table = load(lang)
        missing = [(p, k) for p, k in order if uid(k) not in table]
        unused = [k for k in table if k not in ids]
        print(f"{lang}: {len(order) - len(missing)}/{len(order)} translated, {len(unused)} unused")
        if missing:
            missing_any = True
            out = os.path.join(ROOT, "i18n", f"missing-{lang}.json")
            with open(out, "w", encoding="utf-8") as f:
                json.dump({uid(k): k for _, k in missing}, f, ensure_ascii=False, indent=1)
            print(f"  missing units written to i18n/missing-{lang}.json")
    return 1 if missing_any else 0


def replace_run(run, html):
    frag = BeautifulSoup(html, "html.parser")
    first = run[0]
    for node in list(frag.contents):
        first.insert_before(node)
    for n in run:
        n.extract()


def build_lang(lang, page, table, problems):
    folder, html_lang, direction, play_hl, gsi_locale = LANGS[lang]
    soup = BeautifulSoup(read_page(page), "html.parser")
    for kind, payload, key in list(units(soup)):
        tr = table.get(uid(key))
        if tr is None or tr == "":
            problems.append(f"{page}: untranslated: {key[:90]}")
            continue
        if kind == "run":
            replace_run(payload, tr)
        else:
            el, attr = payload
            el[attr] = tr

    html = soup.find("html")
    html["lang"] = html_lang
    if direction == "rtl":
        html["dir"] = "rtl"
    # Internal links into this language's folder.
    for a in soup.find_all("a", href=True):
        if a.find_parent(class_="lang-list") or a.has_attr("data-keep-href"):
            continue  # the picker, and links meant for the English page, keep their href
        href = a["href"]
        if PAGE_LINK.match(href):
            a["href"] = f"/{folder}{href}"
        elif href.startswith("https://play.google.com/store/apps/details?id=com.audex"):
            a["href"] = f"https://play.google.com/store/apps/details?id=com.audex&hl={play_hl}"
    # Localized Google Play badge, where one exists.
    badge = f"/badges/google-play-badge-{lang}.png"
    if os.path.exists(os.path.join(ROOT, badge.lstrip("/"))):
        for img in soup.find_all("img", src="/badges/google-play-badge.png"):
            img["src"] = badge
    # Picker: mark this language as current.
    for li in soup.select(".lang-list a"):
        if li.get("hreflang") == html_lang:
            li["aria-current"] = "true"
        elif li.has_attr("aria-current"):
            del li["aria-current"]
    for s in soup.select(".lang-current"):
        s.string = lang.split("-")[0].upper()
    # Google sign-in button language (delete-account page).
    for el in soup.select(".g_id_signin"):
        el["data-locale"] = gsi_locale
    # Arabic UI font, loaded only where it's needed.
    if lang == "ar":
        fonts = soup.find("link", href=re.compile(r"fonts\.googleapis\.com/css2"))
        if fonts:
            fonts["href"] = "https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Arabic:wght@400;500;600;700&family=Sora:wght@400;500;600;700;800&display=swap"
    soup.find("html").insert_before(Comment(GENERATED_NOTE.format(lang=lang)))
    out = os.path.join(ROOT, folder, page)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(str(soup))


def build():
    problems = []
    for lang in LANGS:
        table = load(lang)
        for page in PAGES:
            build_lang(lang, page, table, problems)
    if problems:
        print("\n".join(problems))
        print(f"{len(problems)} untranslated unit(s): run `extract` and fill them in.")
        return 1
    print(f"Built {len(LANGS)} languages x {len(PAGES)} pages.")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "build"
    sys.exit(extract() if cmd == "extract" else build())
